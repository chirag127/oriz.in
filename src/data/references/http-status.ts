import type { HttpStatusEntry } from './types';

function mdn(code: number): string {
  return `https://developer.mozilla.org/en-US/docs/Web/HTTP/Status/${code}`;
}

function status(
  code: number,
  name: string,
  category: HttpStatusEntry['category'],
  meaning: string,
  usage: string,
  deprecated = false,
): HttpStatusEntry {
  return { code, name, category, meaning, usage, source: mdn(code), deprecated };
}

